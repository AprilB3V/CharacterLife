/**
 * Start the CharacterLife server and the dsh web UI together, so you can chat with the
 * character in dsh. Run `npm run dsh:install` once first. See docs/DSH.md.
 *
 *   npm run dsh:chat
 *
 * Reads .env from the repository root when present (model settings, CHARACTERLIFE_DB,
 * CHARACTERLIFE_CHARACTER_PACK…). Variables already set in the shell win.
 * CHARACTERLIFE_API_TOKEN is optional here: without it a random token is used for this run.
 * Ctrl+C stops both. Extra arguments go to dsh web, e.g. `npm run dsh:chat -- --port 8820 --no-open`.
 */

import { spawn, spawnSync, type ChildProcess } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { DSH_PROFILE, bundleLinked, dshVersion, profileBundles, quote } from './common.ts'

const ROOT = resolve(import.meta.dirname, '../..')
const envFile = join(ROOT, '.env')
if (existsSync(envFile)) process.loadEnvFile(envFile)

if (!dshVersion()) fail('dsh was not found on PATH. Install DeepSeek Harness first.')
if (!profileBundles()?.includes('characterlife-dsh') || !bundleLinked()) {
  fail(`dsh profile "${DSH_PROFILE}" is not set up. Run: npm run dsh:install`)
}

const hasModel = Boolean(
  process.env.CHARACTERLIFE_MODEL_BASE_URL?.trim() || process.env.CHARACTERLIFE_MODEL_API_KEY?.trim() || process.env.DEEPSEEK_API_KEY?.trim(),
)
if (!hasModel) {
  console.warn('⚠️  No model configured: the character will answer with the offline mock model.')
  console.warn('   Set CHARACTERLIFE_MODEL_BASE_URL / _MODEL / _API_KEY in .env (see docs/MODELS.md).\n')
}

const token = process.env.CHARACTERLIFE_API_TOKEN?.trim() || randomBytes(18).toString('base64url')
const port = Number(process.env.CHARACTERLIFE_PORT?.trim() || 8787)
const host = '127.0.0.1'
const env = { ...process.env, CHARACTERLIFE_API_TOKEN: token, CHARACTERLIFE_PORT: String(port) }

const children: ChildProcess[] = []
let stopping = false

function stopAll(code: number): never {
  stopping = true
  for (const child of children) {
    if (child.exitCode !== null || child.pid === undefined) continue
    // dsh runs through a shell on Windows; kill the whole tree.
    if (process.platform === 'win32') spawnSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], { stdio: 'ignore' })
    else child.kill('SIGTERM')
  }
  process.exit(code)
}

function fail(message: string): never {
  console.error(`❌ ${message}`)
  stopAll(1)
}

process.on('SIGINT', () => stopAll(0))
process.on('SIGTERM', () => stopAll(0))

const server = spawn(process.execPath, [join(ROOT, 'examples/sillytavern/start-server.ts')], { cwd: ROOT, env, stdio: 'inherit' })
children.push(server)
server.on('exit', (code) => {
  if (stopping) return
  console.error(`\nCharacterLife server exited (code ${code}).`)
  stopAll(code ?? 1)
})

const base = `http://${host}:${port}`
const modelId = await waitForModel()

// Point the profile at this run's port and character. Patch configs replace the whole entry config.
const overlayDir = join(ROOT, 'data')
mkdirSync(overlayDir, { recursive: true })
const overlayPath = join(overlayDir, 'dsh-session.patch.yml')
writeFileSync(
  overlayPath,
  [
    '# Generated by npm run dsh:chat on every start; do not edit.',
    '- id: llm-pi-ai',
    "  name: '@deepseek-ai/dsh-llm-pi-ai'",
    '  config:',
    '    providers:',
    '      characterlife:',
    '        api: openai-completions',
    '        apiKeyEnv: CHARACTERLIFE_API_TOKEN',
    `        baseURL: ${base}/v1`,
    '        displayName: CharacterLife',
    '        defaultContextWindow: 1048576',
    '        models:',
    `          - id: ${JSON.stringify(modelId)}`,
    `            name: ${JSON.stringify(modelId.replace(/^characterlife\//, ''))}`,
    '            contextWindow: 1048576',
    '            input:',
    '              - text',
    '- id: agent-default-model',
    "  name: '@deepseek-ai/dsh-agent-default-model'",
    '  config:',
    '    provider: characterlife',
    `    model: ${JSON.stringify(modelId)}`,
    '',
  ].join('\n'),
  'utf8',
)

console.log(`\nStarting dsh (profile "${DSH_PROFILE}", character ${modelId})…`)
console.log('dsh prints a link with a login token and opens it in your browser. Ctrl+C here stops both.\n')
const dshArgs = ['dsh', DSH_PROFILE, '--patch', overlayPath, ...process.argv.slice(2)]
const dsh = spawn(dshArgs.map(quote).join(' '), { cwd: ROOT, env, stdio: 'inherit', shell: true })
children.push(dsh)
dsh.on('exit', (code) => {
  if (stopping) return
  console.log(`\ndsh exited (code ${code}). Stopping the CharacterLife server.`)
  stopAll(code ?? 0)
})

/** Wait until the server answers /v1/models; returns the character's model id. */
async function waitForModel(): Promise<string> {
  const deadline = Date.now() + 60_000
  while (Date.now() < deadline) {
    if (server.exitCode !== null) stopAll(server.exitCode)
    try {
      const res = await fetch(`${base}/v1/models`, { headers: { authorization: `Bearer ${token}` } })
      if (res.ok) {
        const body = (await res.json()) as { data?: Array<{ id?: unknown }> }
        const id = body.data?.find((m) => typeof m.id === 'string')?.id
        if (typeof id === 'string') return id
      }
    } catch {
      // not listening yet
    }
    await new Promise((r) => setTimeout(r, 500))
  }
  fail(`CharacterLife server did not answer on ${base} within 60 s.`)
}
